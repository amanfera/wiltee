#!/usr/bin/env python3
"""Writes the device tree of a wiltee RV64 guest to stdout.

usage: mkdts64.py [--harts N] [--isa rv64imafdc] [--virtio] [--bootargs ARGS]

N harts (Sv39, S-mode, one PLIC S-mode context each), 128 MiB of RAM at 0,
a 16550 UART, a PLIC and, with --virtio, a virtio-mmio block device
(0xF5000000, IRQ 2) and network device (0xF5001000, IRQ 3). The emulator
must run with as many harts (WILTEE_HARTS=N)."""
import argparse

ap = argparse.ArgumentParser()
ap.add_argument("--harts", type=int, default=1)
ap.add_argument("--isa", default="rv64imafdc")
ap.add_argument("--virtio", action="store_true")
ap.add_argument("--bootargs", default="earlycon console=ttyS0")
a = ap.parse_args()
assert 1 <= a.harts <= 16

cpus = "".join(f"""
		cpu{i}: cpu@{i} {{
			device_type = "cpu";
			compatible = "riscv";
			reg = <{i}>;
			riscv,isa = "{a.isa}";
			mmu-type = "riscv,sv39";

			cpu{i}_intc: interrupt-controller {{
				#interrupt-cells = <1>;
				interrupt-controller;
				compatible = "riscv,cpu-intc";
			}};
		}};
""" for i in range(a.harts))
ctxs = " ".join(f"&cpu{i}_intc 9" for i in range(a.harts))
virtio = """
		virtio_mmio@5000000 {
			compatible = "virtio,mmio";
			reg = <0x5000000 0x1000>;
			interrupts = <2>;
		};

		virtio_mmio@5001000 {
			compatible = "virtio,mmio";
			reg = <0x5001000 0x1000>;
			interrupts = <3>;
		};
""" if a.virtio else ""

print(f"""/dts-v1/;

/* Generated by scripts/mkdts64.py --harts {a.harts} --isa {a.isa}{' --virtio' if a.virtio else ''}
 * The wiltee RV64 platform: {a.harts} hart(s) (Sv39), 128 MiB of RAM at 0, a 16550
 * UART and a PLIC{', virtio-mmio block and network devices' if a.virtio else ''}. The timer, IPIs, remote
 * fences and hart start/stop are SBI calls answered by the emulator; `time`
 * advances one tick per instruction (all harts together). */
/ {{
	#address-cells = <2>;
	#size-cells = <2>;
	model = "wiltee";
	compatible = "wiltee,rv64";

	aliases {{
		serial0 = "/soc@f0000000/serial@4000000";
	}};

	chosen {{
		bootargs = "{a.bootargs}";
		stdout-path = "serial0";
	}};

	cpus {{
		#address-cells = <1>;
		#size-cells = <0>;
		timebase-frequency = <10000000>;
{cpus}	}};

	memory@0 {{
		device_type = "memory";
		reg = <0x0 0x00000000 0x0 0x08000000>;
	}};

	soc: soc@f0000000 {{
		#address-cells = <1>;
		#size-cells = <1>;
		compatible = "simple-bus";
		ranges = <0x0 0x0 0xf0000000 0x10000000>;
		interrupt-parent = <&plic0>;

		plic0: interrupt-controller@0 {{
			#interrupt-cells = <1>;
			#address-cells = <0>;
			compatible = "sifive,plic-1.0.0";
			reg = <0x0000000 0x4000000>;
			interrupt-controller;
			interrupts-extended = <{ctxs}>;
			riscv,ndev = <31>;
		}};

		serial@4000000 {{
			compatible = "ns16550";
			reg = <0x4000000 0x100000>;
			interrupts = <1>;
			no-loopback-test;
			clock-frequency = <5000000>;
		}};
{virtio}	}};
}};""")
